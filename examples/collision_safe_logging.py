"""Structured logging when user keys collide with ``LogRecord`` attributes.

Run ``python examples/collision_safe_logging.py``. Two different mechanisms keep the
record's own metadata (``message``, ``name``, ``exc_info`` ...) intact, and they do
**not** behave the same way, so do not assume every collision is renamed:

1. **Reserved keys passed as extra fields** to a ``FunctionLogger`` call (``name``,
   ``message``) are *renamed* to ``extra_<key>``; the value is still emitted.
2. **Keys generated by ``AttributeFlattenFilter``** (``exc`` + ``info`` joined with
   ``separator="_"`` gives ``exc_info``) never overwrite an existing record attribute;
   the generated key is *dropped* (not renamed). A literal extra key that equals a
   generated one also wins over the generated one.

All values are fake. This demonstrates metadata preservation, not secret safety.
"""

from __future__ import annotations

import logging
import sys
from typing import TextIO

from azure_functions_logging import AttributeFlattenFilter, JsonFormatter, get_logger

LOGGER_NAME = "examples.collision_safe_logging"


def emit(stream: TextIO) -> None:
    """Emit one record exercising every collision to ``stream`` as one JSON line."""
    handler = logging.StreamHandler(stream)
    handler.setFormatter(JsonFormatter())
    handler.addFilter(AttributeFlattenFilter(separator="_"))
    target = logging.getLogger(LOGGER_NAME)
    target.addHandler(handler)
    target.setLevel(logging.INFO)
    target.propagate = False
    try:
        get_logger(LOGGER_NAME).info(
            "order accepted",  # record metadata: ``message``
            name="user-supplied-name",  # collides with LogRecord.name -> renamed
            message="user-supplied-message",  # collides with LogRecord.message -> renamed
            exc={"info": "user-supplied-detail"},  # flattens to exc_info -> dropped
            order={"id": 7},  # flattens to order_id -> kept
            a={"b": 1},  # flattens to a_b ...
            a_b=999,  # ... but this literal key wins
        )
    finally:
        target.removeHandler(handler)  # leave the logger as we found it


def main() -> None:
    """Print the JSON record."""
    emit(sys.stdout)


if __name__ == "__main__":
    main()
